"""RetinaAI Streamlit app (M6).

    .venv\\Scripts\\streamlit run app.py

Upload a fundus photograph -> grade (stage 0-4, probabilities, Grad-CAM) -> simulated next stage(s) ->
side-by-side comparison with SSIM/PSNR and a re-grade -> PDF report. Every run is saved to the local history.

Set RETINAGEN_DEMO_MODE=1 for the public demo: only the bundled sample images can be analysed and nothing is
saved (PRD privacy requirement).
"""

from __future__ import annotations

import hashlib
import json
import os

import numpy as np
import pandas as pd
import streamlit as st

import config
from database import db
from prediction.pipeline import Analysis, Pipeline
from prediction.runs import save_run
from preprocessing.fundus import fundus_mask, read_image
from preprocessing.quality import UploadError, validate_upload
from utils.charts import probability_chart
from utils.report import DIFF_SCALE_MAX, build_report
from utils.visuals import colorbar, importance_overlay, label_simulated, sequential_image

DEMO_MODE = os.environ.get("RETINAGEN_DEMO_MODE") == "1"
SAMPLES_DIR = config.STATIC_DIR / "samples"

st.set_page_config(page_title="RetinaAI", layout="wide")


@st.cache_resource(show_spinner="Loading the classifier...")
def get_pipeline() -> Pipeline:
    return Pipeline()


@st.cache_resource
def get_db():
    return db.connect()


def stage_label(k: int) -> str:
    return f"Stage {k} - {config.STAGE_NAMES[k]}"


def disclaimer() -> None:
    st.warning(f"**Not a diagnosis.** {config.DISCLAIMER}", icon=":material/info:")


# ------------------------------------------------------------------ sidebar


def sidebar() -> tuple[int, bool]:
    with st.sidebar:
        st.title("RetinaAI")
        st.caption("Diabetic retinopathy grading and next-stage simulation. Research and education prototype.")
        steps = st.select_slider(
            "Stages to simulate ahead",
            options=[1, 2, 3, 4],
            value=1,
            help="1 shows the next stage. More chains the generators, each fed the previous simulated image.",
        )
        gradcam = st.toggle("Show Grad-CAM", value=True, help="Highlights the regions that most influenced the grade.")
        st.divider()
        st.caption("Models")
        st.caption(f"Classifier: {get_pipeline().cnn_version}")
        for k in range(config.MAX_STAGE):
            ready = config.generator_path(k).exists()
            st.caption(f"Generator {k} to {k + 1}: {'ready' if ready else 'not trained yet'}")
        if DEMO_MODE:
            st.caption("Demo mode: sample images only, nothing is saved.")
    return steps, gradcam


# ------------------------------------------------------------------ analysis view


def render_grade(analysis: Analysis) -> None:
    k = analysis.stage
    st.subheader(f"Detected: {stage_label(k)}")
    st.caption(f"Confidence {analysis.confidence:.0%}  ·  classifier {analysis.model_version}")
    for warning in analysis.quality.warnings:
        st.warning(warning, icon=":material/warning:")

    cols = st.columns([1, 1, 1.4], gap="medium")
    cols[0].image(analysis.cnn_input, caption="Your image after preprocessing (as graded)", width="stretch",
                  alt="Preprocessed fundus photograph")  # fmt: skip
    if analysis.gradcam is not None:
        cols[1].image(importance_overlay(analysis.cnn_input, analysis.gradcam), width="stretch",
                      caption="Grad-CAM: darker blue = more influence on the grade",
                      alt="Fundus photograph tinted blue where the classifier focused")  # fmt: skip
    cols[2].plotly_chart(probability_chart(analysis.probabilities), width="stretch", config={"displayModeBar": False})


def render_simulations(analysis: Analysis) -> None:
    for note in analysis.notes:
        st.info(note, icon=":material/info:")
    if not analysis.simulations:
        return
    st.subheader("Simulated next-stage appearance")
    st.caption(
        "Generated by a model trained on other patients' images: a general picture of what the next stage tends to "
        "look like, not a prediction of this eye's future."
    )
    mask = fundus_mask(analysis.current)
    for sim in analysis.simulations:
        st.markdown(f"**{stage_label(sim.from_stage)} → {stage_label(sim.to_stage)}**")
        cols = st.columns(3, gap="medium")
        cols[0].image(analysis.current, caption="Current retina", width="stretch", alt="Current fundus image")
        cols[1].image(label_simulated(sim.image), caption=f"SIMULATED {stage_label(sim.to_stage)}", width="stretch",
                      alt=f"Simulated fundus image at stage {sim.to_stage}, labelled SIMULATED")  # fmt: skip
        with cols[2]:
            st.image(sequential_image(sim.difference, mask, vmax=DIFF_SCALE_MAX), width="stretch",
                     caption="Difference from the current retina", alt="Map of where the simulated image differs")  # fmt: skip
            st.image(colorbar(512, 12), width="stretch")
            left, right = st.columns(2)
            left.caption("no change")
            right.markdown("<div style='text-align:right'><small>large change</small></div>", unsafe_allow_html=True)
        m = st.columns(3)
        m[0].metric("SSIM", f"{sim.ssim:.3f}", help="Structural similarity to the current retina (1 = identical).")
        m[1].metric("PSNR", f"{sim.psnr:.1f} dB", help="Peak signal-to-noise ratio against the current retina.")
        verdict = "matches the simulated stage" if sim.regrade_matches else "does not match the simulated stage"
        m[2].metric("Classifier re-grade", f"Stage {sim.regraded_stage}", help="The classifier's grade for the simulated image.")
        st.caption(f"The re-grade {verdict}. Generator {sim.generator_version}.")
        st.divider()


def image_source() -> tuple[bytes, str] | None:
    samples = sorted(p for p in SAMPLES_DIR.glob("*") if p.suffix.lower() in config.ALLOWED_EXTENSIONS) if SAMPLES_DIR.exists() else []
    if not DEMO_MODE:
        upload = st.file_uploader(
            "Upload a colour fundus photograph (JPG or PNG, up to 10 MB)", type=["jpg", "jpeg", "png"],
            max_upload_size=config.MAX_UPLOAD_MB,
        )  # fmt: skip
        if upload is not None:
            return upload.getvalue(), upload.name
    if samples:
        choice = st.selectbox("Or try a sample image" if not DEMO_MODE else "Choose a sample image",
                              [None, *samples], format_func=lambda p: "-" if p is None else p.stem)  # fmt: skip
        if choice is not None:
            return choice.read_bytes(), choice.name
    return None


def analyse_tab(steps: int, gradcam: bool) -> None:
    source = image_source()
    if source is None:
        st.markdown(
            "Upload a fundus photograph to get its diabetic retinopathy grade, see which regions drove the grade, "
            "and view a **simulated** image of how the retina could look at the next stage."
        )
        disclaimer()
        return

    data, name = source
    key = (hashlib.sha256(data).hexdigest(), steps, gradcam)
    if st.session_state.get("key") != key:
        try:
            image = validate_upload(name, data)
        except UploadError as exc:
            st.error(str(exc), icon=":material/error:")
            return
        with st.spinner("Grading and simulating..."):
            analysis = get_pipeline().analyze(image, steps=steps, with_gradcam=gradcam)
            if DEMO_MODE:
                run_id, report = None, build_report(analysis)
            else:
                run_id, report_path = save_run(get_db(), analysis)
                report = report_path.read_bytes()
        st.session_state.update(key=key, analysis=analysis, run_id=run_id, report=report)

    analysis, run_id = st.session_state["analysis"], st.session_state["run_id"]
    disclaimer()
    render_grade(analysis)
    st.divider()
    render_simulations(analysis)
    st.download_button(
        "Download PDF report", data=st.session_state["report"], file_name=f"retinagen_run_{run_id or 'demo'}.pdf",
        mime="application/pdf", type="primary", icon=":material/download:",
    )  # fmt: skip
    if run_id is not None:
        st.caption(f"Saved to history as run {run_id}.")


# ------------------------------------------------------------------ history


def history_tab() -> None:
    conn = get_db()
    rows = db.history(conn)
    if not rows:
        st.info("No saved runs yet. Analyse an image and it will appear here.")
        return
    table = pd.DataFrame(
        {
            "Run": [r["prediction_id"] for r in rows],
            "Date (UTC)": [r["created_at"].replace("T", " ")[:16] for r in rows],
            "Grade": [stage_label(r["stage"]) for r in rows],
            "Confidence": [r["confidence"] for r in rows],
            "Simulated up to": [stage_label(r["simulated_to_stage"]) if r["simulated_to_stage"] is not None else "-" for r in rows],
            "Quality warnings": [r["quality_warnings"].replace("\n", "; ") or "-" for r in rows],
        }
    )
    st.caption("Select a run to reopen it.")
    event = st.dataframe(
        table, hide_index=True, on_select="rerun", selection_mode="single-row", width="stretch",
        column_config={"Confidence": st.column_config.NumberColumn(format="percent")},
    )  # fmt: skip
    if event.selection.rows:
        show_run(conn, int(table.iloc[event.selection.rows[0]]["Run"]))


def show_run(conn, prediction_id: int) -> None:
    prediction, generated = db.get_run(conn, prediction_id)
    st.subheader(f"Run {prediction_id}: {stage_label(prediction['stage'])}")
    disclaimer()
    cols = st.columns([1, 1.4], gap="medium")
    cols[0].image(read_image(config.ROOT / prediction["image_path"]), caption="Uploaded image", width="stretch")
    probabilities = np.array(json.loads(prediction["probabilities_json"]))
    cols[1].plotly_chart(probability_chart(probabilities), width="stretch", config={"displayModeBar": False},
                         key=f"history_probs_{prediction_id}")  # fmt: skip
    for g in generated:
        st.markdown(f"**{stage_label(g['from_stage'])} → {stage_label(g['to_stage'])}** (simulated)")
        c = st.columns([1, 2])
        c[0].image(read_image(config.ROOT / g["image_path"]), width="stretch", caption=f"SIMULATED stage {g['to_stage']}")
        c[1].markdown(f"SSIM {g['ssim']:.3f} · PSNR {g['psnr']:.1f} dB · re-graded as {stage_label(g['regraded_stage'])}")
    if prediction["report_path"] and (config.ROOT / prediction["report_path"]).exists():
        st.download_button(
            "Download this run's PDF report", data=(config.ROOT / prediction["report_path"]).read_bytes(),
            file_name=f"retinagen_run_{prediction_id}.pdf", mime="application/pdf", key=f"report_{prediction_id}",
        )  # fmt: skip


# ------------------------------------------------------------------ about


def about_tab() -> None:
    st.markdown(
        f"""
**What it does.** RetinaAI grades a colour fundus photograph into the five diabetic retinopathy stages
(0 No DR, 1 Mild, 2 Moderate, 3 Severe, 4 Proliferative) with an EfficientNetB0 classifier, then shows a
**simulated** image of the next stage made by a transition generator, and compares the two.

**How the simulations are made.** One generator per transition (0→1, 1→2, 2→3, 3→4), trained without paired
before/after photos (CycleGAN-style): it learns what the next stage looks like *in general* and adds that to
the uploaded retina while keeping its vessels and optic disc. It cannot know how *this* eye will progress, or
when.

**What it is not.** It is not a medical device: it gives no diagnosis, treatment or referral advice.

**Privacy.** {"This public demo only analyses the bundled sample images and saves nothing." if DEMO_MODE else
"Running locally, images never leave this computer; runs are stored in a local database."}
"""
    )
    disclaimer()


def main() -> None:
    if not config.CNN_MODEL_PATH.exists():
        st.error("No classifier found at models/model.keras. Train it with `python -m cnn.train` (see README).")
        st.stop()
    steps, gradcam = sidebar()
    names = ["Analyse", "About"] if DEMO_MODE else ["Analyse", "History", "About"]
    tabs = dict(zip(names, st.tabs(names)))
    with tabs["Analyse"]:
        analyse_tab(steps, gradcam)
    if "History" in tabs:
        with tabs["History"]:
            history_tab()
    with tabs["About"]:
        about_tab()


main()
